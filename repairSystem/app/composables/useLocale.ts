export function useLocale() {
  const locale = useState<string>('app:locale', () => 'uz')

  function setLocale(lang: string) {
    const normalized = lang === 'ru' ? 'ru' : lang === 'en' ? 'en' : 'uz'
    locale.value = normalized
    if (process.client) {
      try {
        localStorage.setItem('repair_lang', normalized)
      } catch (e) {
        void e
      }
      document.documentElement.setAttribute('lang', normalized)
    }
  }

  const t = (key: string) => {
    return (
      translations[locale.value]?.[key] ||
      translations.en?.[key] ||
      translations.uz[key] ||
      key
    )
  }

  onMounted(() => {
    if (!process.client) return
    try {
      const stored = localStorage.getItem('repair_lang')
      if (stored === 'ru' || stored === 'uz' || stored === 'en') {
        locale.value = stored
      } else {
        locale.value = 'uz'
      }
      document.documentElement.setAttribute('lang', locale.value)
    } catch (e) {
      void e
    }
  })

  return { locale, setLocale, t }
}
